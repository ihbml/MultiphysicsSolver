"""Unified Developer & Agent CLI Entrypoint (Blueprint §3.3.3).

Commands:
  python tools/dev.py build            # Build C++20 DLL via CMake + check C-ABI layout
  python tools/dev.py verify           # Build + run fast L0 ABI & FVM invariant gates (< 60s)
  python tools/dev.py verify --full    # Build + L0 + reproducible E2E mesher suite
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time

REPO_ROOT = Path(__file__).resolve().parents[1]
NATIVE_SRC = REPO_ROOT / "backend" / "meshing" / "native"
NATIVE_BUILD = NATIVE_SRC / "build"

TIER_BUDGETS: dict[str, dict[str, float | int]] = {
    "L0": {"timeout_s": 60.0, "max_octree_nodes": 4_000_000, "ram_limit_gb": 2.0},
    "L1": {"timeout_s": 300.0, "max_octree_nodes": 4_000_000, "ram_limit_gb": 4.0},
    "L2": {"timeout_s": 600.0, "max_octree_nodes": 12_000_000, "ram_limit_gb": 16.0},
}


def _find_cmake() -> str:
    found = shutil.which("cmake")
    if found:
        return found
    cache_file = NATIVE_BUILD / "CMakeCache.txt"
    if cache_file.is_file():
        for line in cache_file.read_text(encoding="utf-8", errors="ignore").splitlines():
            if line.startswith("# It was generated by CMake:"):
                cand = line.split(":", 1)[1].strip()
                if Path(cand).is_file():
                    return cand
    vs_candidates = [
        r"C:\Program Files\Microsoft Visual Studio\2022\Community\Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin\cmake.exe",
        r"C:\Program Files\Microsoft Visual Studio\2022\Professional\Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin\cmake.exe",
        r"C:\Program Files\Microsoft Visual Studio\2022\BuildTools\Common7\IDE\CommonExtensions\Microsoft\CMake\CMake\bin\cmake.exe",
    ]
    for cand in vs_candidates:
        if Path(cand).is_file():
            return cand
    return "cmake"


def _run(cmd: list[str], env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        cmd,
        cwd=str(REPO_ROOT),
        env=env,
        text=True,
        capture_output=True,
    )


def cmd_build() -> int:
    t0 = time.perf_counter()
    cmake_bin = _find_cmake()
    NATIVE_BUILD.mkdir(parents=True, exist_ok=True)
    if not (NATIVE_BUILD / "CMakeCache.txt").exists():
        cfg = _run([cmake_bin, "-S", str(NATIVE_SRC), "-B", str(NATIVE_BUILD)])
        if cfg.returncode != 0:
            print(cfg.stdout)
            print(cfg.stderr, file=sys.stderr)
            return cfg.returncode

    bld = _run([cmake_bin, "--build", str(NATIVE_BUILD), "--config", "Release"])
    if bld.returncode != 0:
        print(bld.stdout)
        print(bld.stderr, file=sys.stderr)
        return bld.returncode

    abi = _run([sys.executable, str(REPO_ROOT / "tools" / "abi_gen.py"), "--check"])
    if abi.returncode != 0:
        print(abi.stdout)
        print(abi.stderr, file=sys.stderr)
        return abi.returncode

    dt = time.perf_counter() - t0
    print(f"[BUILD OK] cfd_mesher_native Release built & ABI verified in {dt:.1f}s")
    return 0


def cmd_verify(full: bool = False, skip_build: bool = False, include_slow: bool = False) -> int:
    if skip_build:
        abi = _run([sys.executable, str(REPO_ROOT / "tools" / "abi_gen.py"), "--check"])
        if abi.returncode != 0:
            print(abi.stdout)
            print(abi.stderr, file=sys.stderr)
            return abi.returncode
        print(abi.stdout.strip())
    else:
        rc = cmd_build()
        if rc != 0:
            return rc

    if include_slow:
        tier = "L2"
        targets = [
            "tests/test_sprint1_audit_and_invariants.py",
            "tests/test_sprint2_passes_and_snapping.py",
            "tests/test_sprint2_scale_and_hardening.py",
            "tests/test_sprint3_features_and_scale.py",
            "tests/e2e_mesher_suite",
        ]
        marker_expr = "not scale_5m and not wsl_checkmesh and not fluent_ref"
    elif full:
        tier = "L1"
        targets = [
            "tests/test_sprint1_audit_and_invariants.py",
            "tests/test_sprint2_passes_and_snapping.py",
            "tests/test_sprint2_scale_and_hardening.py",
            "tests/test_sprint3_features_and_scale.py",
            "tests/e2e_mesher_suite",
        ]
        marker_expr = "not slow and not scale_5m and not wsl_checkmesh and not fluent_ref"
    else:
        tier = "L0"
        targets = [
            "tests/test_sprint1_audit_and_invariants.py",
            "tests/test_sprint2_passes_and_snapping.py",
            "tests/test_sprint2_scale_and_hardening.py",
            "tests/test_sprint3_features_and_scale.py",
        ]
        marker_expr = "not scale_5m and not wsl_checkmesh and not fluent_ref"

    budget = TIER_BUDGETS[tier]
    timeout_s = float(budget["timeout_s"])

    env = os.environ.copy()
    env.setdefault("CFD_STRICT_NATIVE", "1")
    env.setdefault("CFD_MAX_OCTREE_NODES", str(int(budget["max_octree_nodes"])))
    env.setdefault("CFD_TEST_RAM_LIMIT_GB", str(budget["ram_limit_gb"]))
    env.setdefault("OMP_NUM_THREADS", str(min(10, os.cpu_count() or 4)))

    pytest_cmd = [
        sys.executable,
        "-m",
        "pytest",
        *targets,
        "-m",
        marker_expr,
        "-q",
        "--tb=short",
    ]
    t0 = time.perf_counter()
    res = _run(pytest_cmd, env=env)
    dt = time.perf_counter() - t0

    cache_dir = REPO_ROOT / ".cache"
    log_path = cache_dir / f"last_verify_{tier}.log"
    try:
        cache_dir.mkdir(parents=True, exist_ok=True)
        log_path.write_text(res.stdout + "\n" + res.stderr, encoding="utf-8")
    except OSError as exc:
        print(f"[WARN] Could not write {log_path}: {exc}", file=sys.stderr)

    lines = [ln for ln in res.stdout.strip().splitlines() if ln.strip()]
    if res.returncode == 0:
        if dt > timeout_s:
            print(
                f"[VERIFY BUDGET EXCEEDED] {tier} took {dt:.1f}s > {timeout_s:.1f}s limit",
                file=sys.stderr,
            )
            return 2
        summary = lines[-1] if lines else "all passed"
        print(f"[VERIFY OK] {tier} {summary} ({dt:.1f}s / {timeout_s:.0f}s budget)")
        return 0

    print(f"[VERIFY FAILED] {tier} ({dt:.1f}s) — full log: {log_path}")
    for ln in lines[-35:]:
        print(ln)
    if res.stderr.strip():
        print(res.stderr.strip()[-1000:], file=sys.stderr)
    return res.returncode


def main() -> int:
    parser = argparse.ArgumentParser(description="CFDSolver unified build & verification runner.")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    p_ver = sub.add_parser("verify")
    p_ver.add_argument("--full", action="store_true", help="Run L1 fast E2E suite in addition to L0")
    p_ver.add_argument(
        "--all",
        dest="include_slow",
        action="store_true",
        help="Run L2 E2E suite including @slow tests (excluding scale_5m/wsl_checkmesh/fluent_ref)",
    )
    p_ver.add_argument(
        "--skip-build",
        action="store_true",
        help="Skip CMake build step (still verifies C-ABI layout against native DLL)",
    )
    args = parser.parse_args()

    if args.cmd == "build":
        return cmd_build()
    if args.cmd == "verify":
        return cmd_verify(full=args.full, skip_build=args.skip_build, include_slow=args.include_slow)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
