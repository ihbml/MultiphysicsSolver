#!/usr/bin/env python3
"""Generate an unrolled analytic sparse species Jacobian from mass-action JSON."""

import json
import pathlib
import sys


def generate(source: pathlib.Path, destination: pathlib.Path):
    mechanism = json.loads(source.read_text())
    names = mechanism["species"]
    weights = mechanism["molecular_weights"]
    reactions = mechanism["reactions"]
    n = len(names)
    if n == 0 or len(set(names)) != n or len(weights) != n or any(w <= 0 for w in weights):
        raise ValueError("invalid species/molecular weights")
    sparse = [set() for _ in names]
    for reaction in reactions:
        for name, power in reaction["reactants"].items():
            if name not in names or power <= 0:
                raise ValueError("unknown reactant or non-positive reaction order")
        for name in reaction["net"]:
            if name not in names:
                raise ValueError("unknown net species")
            sparse[names.index(name)].update(names.index(x) for x in reaction["reactants"])
        if abs(sum(weights[names.index(x)] * nu for x, nu in reaction["net"].items())) > 1e-10:
            raise ValueError("reaction must conserve mass")
    columns = [sorted(row) for row in sparse]
    rowptr = [0]
    for row in columns:
        rowptr.append(rowptr[-1] + len(row))
    col = [x for row in columns for x in row]
    lines = [
        "#pragma once",
        "// Generated by native/tools/generate_mechanism.py; edit the JSON, not this file.",
        "#include <cmath>",
        "#ifdef __CUDACC__",
        "#define CONTINUUM_HD __host__ __device__",
        "#else",
        "#define CONTINUUM_HD",
        "#endif",
        "namespace continuum::chemistry {",
        f"struct {mechanism['name']} {{",
        f"  static constexpr int nspecies = {n};",
        f"  static constexpr int nnz = {len(col)};",
        f"  inline static constexpr int rowptr[{n + 1}] = {{{', '.join(map(str, rowptr))}}};",
        f"  inline static constexpr int col[{len(col)}] = {{{', '.join(map(str, col))}}};",
        "  CONTINUUM_HD static constexpr int row_start(int i) {",
        "    switch (i) {" + " ".join(f"case {i}: return {v};" for i, v in enumerate(rowptr)) + " default: return 0; }",
        "  }",
        "  CONTINUUM_HD static constexpr int column(int i) {",
        "    switch (i) {" + " ".join(f"case {i}: return {v};" for i, v in enumerate(col)) + " default: return 0; }",
        "  }",
        "  CONTINUUM_HD static void eval(double t, double rho, const double* y, double* w, double* jac) {",
        f"    for (int k = 0; k < {n}; ++k) w[k] = 0.0;",
        f"    for (int k = 0; k < {len(col)}; ++k) jac[k] = 0.0;",
    ]
    for r, reaction in enumerate(reactions):
        reactants = [(names.index(name), float(power)) for name, power in reaction["reactants"].items()]
        factor = f"({float(reaction['A']):.17g} * ::exp(-{float(reaction['E']):.17g} / (8.31446261815324 * t)))"
        product = " * ".join(f"::pow((rho * y[{j}] / {weights[j]:.17g}), {power:.17g})" for j, power in reactants)
        lines.append(f"    const double rate{r} = {factor}" + (f" * {product};" if product else ";"))
        for j, power in reactants:
            terms = [f"{power:.17g}", f"(rho / {weights[j]:.17g})"]
            for k, exponent in reactants:
                terms.append(f"::pow((rho * y[{k}] / {weights[k]:.17g}), {exponent - (1 if j == k else 0):.17g})")
            lines.append(f"    const double dr{r}_{j} = {factor} * " + " * ".join(terms) + ";")
        for name, nu in reaction["net"].items():
            i = names.index(name)
            coeff = float(nu) * weights[i]
            lines.append(f"    w[{i}] += ({coeff:.17g} / rho) * rate{r};")
            for j, _ in reactants:
                pos = rowptr[i] + columns[i].index(j)
                lines.append(f"    jac[{pos}] += ({coeff:.17g} / rho) * dr{r}_{j};")
    lines += ["  }", "};", "} // namespace continuum::chemistry", "#undef CONTINUUM_HD", ""]
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_mechanism.py mechanism.json generated.hpp")
    generate(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]))